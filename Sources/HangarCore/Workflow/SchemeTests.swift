import Foundation

/// Which schemes run tests, read from the repository without Xcode: a shared scheme's `.xcscheme` lists test targets or
/// a test plan in its Test action, and Xcode generates schemes from a local Swift package's `Package.swift`.
///
/// `xcodebuild test` on a scheme whose Test action is empty fails at once ("Scheme X is not currently configured for
/// the test action", exit 66), so a test action on such a scheme can only fail.
public enum SchemeTests {
    /// Whether a scheme file's Test action has something to run.
    public static func hasTests(schemeXML: String) -> Bool {
        schemeXML.contains("<TestableReference") || schemeXML.contains("<TestPlanReference")
    }

    /// `<…>/xcshareddata/xcschemes/<scheme>.xcscheme` paths in `paths`, outside `Pods`, `.build` and the like.
    public static func sharedSchemeFiles(named scheme: String, in paths: [String]) -> [String] {
        let suffix = "xcshareddata/xcschemes/\(scheme).xcscheme"
        return paths.filter { ($0 == suffix || $0.hasSuffix("/" + suffix)) && WorkflowDetector.isUsable($0) }.sorted()
    }

    /// The schemes Xcode generates from a package that run tests. A test target named `<product>Tests` joins that
    /// library or executable product's scheme; any other test target gets a scheme of its own, named after it.
    /// (BatFiKit: `AppSharedTests` runs in the `AppShared` scheme, `LicenseTokenTests` in its own.)
    public static func generatedSchemesWithTests(packageSwift text: String) -> [String] {
        let products = Set(names(after: #"\.(?:library|executable)\(\s*name:\s*""#, in: text))
        let tests = names(after: #"\.testTarget\(\s*name:\s*""#, in: text)
        var schemes: [String] = []
        for test in tests {
            let product = test.hasSuffix("Tests") ? String(test.dropLast("Tests".count)) : nil
            let scheme = product.flatMap { products.contains($0) ? $0 : nil } ?? test
            if !schemes.contains(scheme) { schemes.append(scheme) }
        }
        return schemes
    }

    /// Each string literal that follows `prefix` (a regular expression ending at the opening quote).
    private static func names(after prefix: String, in text: String) -> [String] {
        guard let expression = try? NSRegularExpression(pattern: prefix + #"([^"\\]+)""#) else { return [] }
        let range = NSRange(text.startIndex..., in: text)
        return expression.matches(in: text, range: range).compactMap { match in
            Range(match.range(at: 1), in: text).map { String(text[$0]) }
        }
    }

    /// Why a test action on `scheme` cannot run, from its shared scheme files' contents (`files`, path → text, for
    /// the paths `sharedSchemeFiles` found); nil when one of them has tests, or when there is none to judge by (the
    /// scheme may be generated by Xcode or private to someone's checkout).
    public static func problem(scheme: String, files: [String: String]) -> String? {
        guard !files.isEmpty, !files.values.contains(where: hasTests) else { return nil }
        let path = files.keys.sorted()[0]
        return "Scheme “\(scheme)” has no tests: the Test action in \(path) lists no test targets or test plan, so `xcodebuild test` fails right away. Set the test action to a scheme that has tests (the workflow editor and suggest_workflow mark them)."
    }
}
